# Builds VibeVideo AI (the vibevideo-ai branch): its editions and installers.
#   powershell -ExecutionPolicy Bypass -File build-ai.ps1                       # x64 + arm64 installers -> dist\
#   powershell -ExecutionPolicy Bypass -File build-ai.ps1 -Editions x64         # just one
#   powershell -ExecutionPolicy Bypass -File build-ai.ps1 -SkipInstaller        # apps only -> publish\vibevideo-ai-<edition>
# Output: dist\VibeVideoAI-Setup-<version>-<edition>.exe and dist\VibeVideoAI-SHA256SUMS.txt.
# The AI models aren't in the installer: the app downloads them on first use (SHA-256 checked).
param(
    [string]$Version = "0.1.0",
    [ValidateSet("x64", "arm64")]
    [string[]]$Editions = @("x64", "arm64"),
    [switch]$SkipInstaller
)
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$project = Join-Path $root "src\VibePlayer\VibePlayer.csproj"
$publishRoot = Join-Path $root "publish"
$dist = Join-Path $root "dist"
$env:DOTNET_CLI_TELEMETRY_OPTOUT = '1'
$env:DOTNET_NOLOGO = '1'

function Find-Tool([string[]]$candidates) {
    foreach ($c in $candidates) { if ($c -and (Test-Path $c)) { return $c } }
    return $null
}

$dotnetCmd = Get-Command dotnet -ErrorAction SilentlyContinue
$dotnet = Find-Tool @("$env:LOCALAPPDATA\Microsoft\dotnet\dotnet.exe", $(if ($dotnetCmd) { $dotnetCmd.Source }))
if (-not $dotnet) { throw ".NET SDK not found. Install the .NET 10 SDK from https://dot.net" }
$iscc = Find-Tool @(
    "$env:LOCALAPPDATA\Programs\Inno Setup 6\ISCC.exe",
    "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe",
    "$env:ProgramFiles\Inno Setup 6\ISCC.exe")
if (-not $iscc -and -not $SkipInstaller) { throw "Inno Setup 6 not found. Install it from https://jrsoftware.org/isdl.php" }

$running = Get-Process VibeVideoAI -ErrorAction SilentlyContinue | Where-Object { $_.Path -and $_.Path.StartsWith($publishRoot, [StringComparison]::OrdinalIgnoreCase) }
if ($running) { throw "VibeVideo AI is running from $publishRoot - close it and run the build again." }

foreach ($edition in $Editions) {
    $out = Join-Path $publishRoot "vibevideo-ai-$edition"
    Write-Host "==> Publishing VibeVideo AI $Version ($edition)" -ForegroundColor Cyan
    if (Test-Path $out) { Remove-Item $out -Recurse -Force }
    & $dotnet publish $project -c Release -f net10.0-windows10.0.19041.0 -r "win-$edition" --self-contained true -o $out -p:DebugType=none -p:Version=$Version -p:VibeEdition=$edition
    if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed for $edition" }

    # VLC plugin cache (instant start-up instead of scanning ~320 plugin DLLs); ARM64 binaries can't run on x64.
    if ($edition -eq "x64") {
        $cache = Join-Path $out "libvlc\win-x64\plugins\plugins.dat"
        if (Test-Path $cache) { Remove-Item $cache -Force }
        $p = Start-Process (Join-Path $out "VibeVideoAI.exe") -ArgumentList "--build-plugin-cache" -PassThru -Wait
        if ($p.ExitCode -ne 0 -or -not (Test-Path $cache)) { throw "Could not build the VLC plugin cache" }
    }
    else {
        Write-Host "    (no plugin cache for ARM64)" -ForegroundColor Yellow
    }
}

if ($SkipInstaller) {
    Write-Host "Done: $publishRoot" -ForegroundColor Green
    return
}

# ---- file associations (generated from MediaFormats.cs so app & installer agree; same as build.ps1) ----
$formats = Get-Content (Join-Path $root "src\VibePlayer\Core\MediaFormats.cs") -Raw -Encoding UTF8
function Get-Extensions([string]$name) {
    $m = [regex]::Match($formats, "$name\s*=\s*\{([^}]*)\}")
    if (-not $m.Success) { throw "Could not read $name from MediaFormats.cs" }
    return [regex]::Matches($m.Groups[1].Value, '"([^"]+)"') | ForEach-Object { $_.Groups[1].Value }
}
$extensions = @(Get-Extensions "VideoExtensions") + @(Get-Extensions "AudioExtensions")
$lines = @("; Generated by build-ai.ps1 - do not edit")
foreach ($ext in $extensions) {
    $lines += "Root: HKA; Subkey: ""Software\Classes\.$ext\OpenWithProgids""; ValueType: string; ValueName: ""{#ProgId}""; ValueData: """"; Flags: uninsdeletevalue; Tasks: fileassoc"
    $lines += "Root: HKA; Subkey: ""Software\{#AppName}\Capabilities\FileAssociations""; ValueType: string; ValueName: "".$ext""; ValueData: ""{#ProgId}""; Tasks: fileassoc"
    $lines += "Root: HKA; Subkey: ""Software\Classes\Applications\{#AppExe}\SupportedTypes""; ValueType: string; ValueName: "".$ext""; ValueData: """""
}
Set-Content -Path (Join-Path $root "installer\associations.iss") -Value $lines -Encoding UTF8

New-Item -ItemType Directory -Force $dist | Out-Null
foreach ($edition in $Editions) {
    Write-Host "==> Compiling installer ($edition)" -ForegroundColor Cyan
    & $iscc /Q "/DAppVersion=$Version" "/DEdition=$edition" (Join-Path $root "installer\VibeVideoAI.iss")
    if ($LASTEXITCODE -ne 0) { throw "Inno Setup failed for $edition" }
}

$setups = Get-ChildItem $dist -Filter "VibeVideoAI-Setup-$Version-*.exe" | Sort-Object Name
$sums = $setups | ForEach-Object { "{0}  {1}" -f (Get-FileHash $_.FullName -Algorithm SHA256).Hash.ToLowerInvariant(), $_.Name }
Set-Content -Path (Join-Path $dist "VibeVideoAI-SHA256SUMS.txt") -Value $sums -Encoding ASCII
foreach ($s in $setups) {
    $mb = $s.Length / 1MB
    $color = if ($s.Length -ge 100MB) { "Red" } else { "Green" }
    Write-Host ("    {0}  {1:N0} bytes ({2:0.0} MB)" -f $s.Name, $s.Length, $mb) -ForegroundColor $color
    if ($s.Length -ge 100MB) { Write-Warning "$($s.Name) is over GitHub's 100 MB file limit." }
}
Write-Host "Done: $dist" -ForegroundColor Green
